<script>
document.addEventListener('DOMContentLoaded', () => {
    const modal = document.getElementById('partner-modal');
    const closeBtn = document.getElementById('close-partner-modal');
    const openBtns = document.querySelectorAll('#open-partner-modal, .request-tier-btn, .select-tier-btn');
    const tierSelect = document.getElementById('modal-tier-select');

    openBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            if (btn.dataset.tier && tierSelect) {
                tierSelect.value = btn.dataset.tier;
            }
            modal.classList.remove('hidden');
        });
    });

    closeBtn.addEventListener('click', () => modal.classList.add('hidden'));
    modal.addEventListener('click', (e) => {
        if (e.target === modal) modal.classList.add('hidden');
    });

    const form = document.getElementById('partner-modal-form');
    const msg = document.getElementById('partner-msg');

    form.addEventListener('submit', async (e) => {
        e.preventDefault();
        const submitBtn = form.querySelector('button[type="submit"]');
        submitBtn.disabled = true;
        submitBtn.textContent = 'Transmitting Partner Inquiry...';

        const formData = new FormData(form);
        const json = Object.fromEntries(formData.entries());

        try {
            const res = await fetch('<?= url('/api/partner') ?>', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(json)
            });
            const data = await res.json();

            msg.classList.remove('hidden', 'bg-red-950/80', 'text-red-300', 'bg-emerald-950/80', 'text-lime-300');
            if (data.success) {
                msg.classList.add('bg-emerald-950/80', 'text-lime-300', 'border', 'border-lime-accent/40');
                msg.textContent = data.message;
                form.reset();
            } else {
                msg.classList.add('bg-red-950/80', 'text-red-300', 'border', 'border-red-500/40');
                msg.textContent = data.message;
            }
        } catch (err) {
            msg.classList.remove('hidden');
            msg.classList.add('bg-red-950/80', 'text-red-300');
            msg.textContent = 'Network error. Please try again.';
        } finally {
            submitBtn.disabled = false;
            submitBtn.innerHTML = '<span>Submit & Receive Confidential Proposal</span><i data-lucide="arrow-right" class="w-4 h-4"></i>';
            if (typeof lucide !== 'undefined') lucide.createIcons();
        }
    });
});
</script>